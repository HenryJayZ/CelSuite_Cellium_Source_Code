#!/usr/bin/env python3
"""Regenerate the OFFLINE RESOLUTION LOCK inside the app's build.gradle.kts.

Why: the offline kit's Maven cache holds exactly ONE version of most artifacts.
Without forcing them, Gradle asks Maven for versions that were never cached and
`--offline` fails. This walks the cache and forces every single-version artifact,
leaving multi-version groups to the explicit rules already in the file.

Usage (no network, ever):
    /home/henry/Documents/Projects/Python/venv/bin/python tools/lock_offline.py
"""
import os
import re
from pathlib import Path

KIT = Path("/home/henry/Documents/Projects/Kotlin/gradle-home/caches/modules-2/files-2.1")
APP = Path(__file__).resolve().parent.parent / "Android" / "cellium-app" / "app" / "build.gradle.kts"

# Groups where several versions legitimately coexist -> never auto-forced.
SKIP_GROUPS = {
    "org.jetbrains.kotlin", "org.jetbrains.kotlinx", "com.android.tools.build",
    "com.android", "androidx.annotation", "com.google.protobuf", "com.google.firebase",
    "com.google.android.gms", "com.google.android.play", "androidx.core",
    "com.google.guava", "com.google.errorprone",
}


def main() -> int:
    if not KIT.is_dir():
        print(f"FATAL: cache not found: {KIT}", flush=True)
        return 1
    forces: list[str] = []
    multi = 0
    for gdir in sorted(p for p in KIT.iterdir() if p.is_dir()):
        g = gdir.name
        for adir in sorted(p for p in gdir.iterdir() if p.is_dir()):
            versions = [p.name for p in adir.iterdir() if p.is_dir()]
            if g in SKIP_GROUPS:
                multi += 1
                continue
            if len(versions) == 1:
                forces.append(f'        force("{g}:{adir.name}:{versions[0]}")')
            else:
                multi += 1
    text = APP.read_text(encoding="utf-8")
    body = "\n".join(forces) + (
        '\n        force("com.google.guava:guava:32.1.3-android")\n'
        '        force("com.google.guava:failureaccess:1.0.1")\n'
        '        force("com.google.guava:listenablefuture:9999.0-empty-to-avoid-conflict-with-guava")\n'
        '        force("com.google.errorprone:error_prone_annotations:2.26.0")\n'
    )
    block = (
        "// ─────────────────────────────────────────────────────────────────────────────\n"
        "// OFFLINE RESOLUTION LOCK (auto-generated by tools/lock_offline.py)\n"
        "// Single-version artifacts in the kit cache are forced so `--offline` resolves.\n"
        "// Regenerate after adding any dependency; never hand-edit the force list.\n"
        "// ─────────────────────────────────────────────────────────────────────────────\n"
        "configurations.all {\n    resolutionStrategy {\n" + body +
        "        eachDependency {\n"
        '            if (requested.group == "androidx.activity") useVersion("1.9.0")\n'
        '            if (requested.group == "androidx.lifecycle") useVersion("2.8.4")\n'
        "        }\n    }\n}\n"
    )
    text = re.sub(r"\nconfigurations\.all \{.*?\n\}\n", "\n", text, flags=re.S)
    APP.write_text(text.rstrip() + "\n" + block, encoding="utf-8")
    print(f"forced {len(forces)} artifacts; skipped {multi} multi-version/skipped entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
