package com.henny.cellium.ai

import com.henny.cellium.data.local.ProviderProfileEntity

data class ProviderCatalogEntry(
    val id: String,
    val name: String,
    val iconKey: String,
    val category: String,
    val protocol: String = "openai",
    val baseUrl: String,
    val defaultModel: String,
    val sampleModels: List<String> = listOf(defaultModel),
    val requiresKey: Boolean = true,
    val popular: Boolean = false,
) {
    fun toEntity(existingKey: String = ""): ProviderProfileEntity = ProviderProfileEntity(
        id = id,
        name = name,
        badge = iconKey,
        protocol = protocol,
        baseUrl = baseUrl,
        apiKey = existingKey,
        selectedModel = if (requiresKey) "" else defaultModel,
        cachedModelsJson = if (requiresKey) "[]" else ProviderPresets.encodeModels(sampleModels),
        requiresKey = requiresKey,
        isCustom = id == ProviderPresets.ID_CUSTOM,
    )
}

